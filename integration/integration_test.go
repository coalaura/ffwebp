var executable = "ffwebp"

func TestMain(m *testing.M) {
	os.Exit(testMain(m))
}

func testMain(m *testing.M) int {
	tmp, err := os.MkdirTemp("", "ffwebp-bin-*")
	if err != nil {
		fmt.Fprintln(os.Stderr, err)

		return 1
	}

	defer os.RemoveAll(tmp)

	if runtime.GOOS == "windows" {
		executable += ".exe"
	}

	executable = filepath.Join(tmp, executable)

	root, err := findRepoRoot()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)

		return 1
	}

	build := icmd.Command("go", "build", "-tags=full", "-o", executable, "./cmd/ffwebp")

	build.Dir = root

	res := icmd.RunCmd(build)
	if res.ExitCode != 0 {
		fmt.Fprintln(os.Stderr, res.Combined())

		return res.ExitCode
	}

	return m.Run()
}

func TestFixtureChecksums(t *testing.T) {
	data, err := os.ReadFile(filepath.Join(fixturesDir, "SHA256SUMS"))
	if err != nil {
		t.Fatal(err)
	}

	for line := range strings.SplitSeq(strings.TrimSpace(string(data)), "\n") {
		want, path, ok := strings.Cut(line, "  ")
		if !ok {
			t.Fatalf("invalid checksum entry: %q", line)
		}

		content, err := os.ReadFile(filepath.Join(fixturesDir, path))
		if err != nil {
			t.Fatal(err)
		}

		got := fmt.Sprintf("%x", sha256.Sum256(content))
		if got != want {
			t.Errorf("fixture changed: %s (got %s, want %s); regenerate the corpus", path, got, want)
		}
	}
}

// The oracle is generated by independent tools, never by ffwebp's encoders.
func TestCLI_FixtureDecode(t *testing.T) {
	for _, test := range fixtures(t) {
		t.Run(filepath.Base(test.File), func(t *testing.T) {
			t.Log(test.Purpose)

			out := filepath.Join(t.TempDir(), "decoded.png")

			arguments := []string{"-s", "--sniff", "-i", filepath.Join(fixturesDir, test.File), "-o", out, "--frame", "0"}
			arguments = append(arguments, test.Arguments...)

			run(t, icmd.Command(executable, arguments...))
			assertPixelsWithin(t, readPNG(t, out), readPNG(t, filepath.Join(fixturesDir, test.Reference[0])), test.Tolerance)
		})
	}
}

func TestCLI_FixtureAnimation(t *testing.T) {
	for _, test := range fixtures(t) {
		if len(test.Delays) == 0 {
			continue
		}

		t.Run(filepath.Base(test.File), func(t *testing.T) {
			dir := t.TempDir()
			input := filepath.Join(fixturesDir, test.File)
			output := filepath.Join(dir, "animation.gif")

			run(t, icmd.Command(executable, "-s", "-i", input, "-o", output))

			data, err := os.ReadFile(output)
			if err != nil {
				t.Fatal(err)
			}

			actual, err := gif.DecodeAll(bytes.NewReader(data))
			if err != nil {
				t.Fatal(err)
			}

			if len(actual.Image) != len(test.Reference) || actual.LoopCount != test.Loops {
				t.Fatalf("got %d frames, loop=%d; want %d, loop=%d", len(actual.Image), actual.LoopCount, len(test.Reference), test.Loops)
			}

			elapsed := 0

			for index, reference := range test.Reference {
				expected := readPNG(t, filepath.Join(fixturesDir, reference))

				if actual.Delay[index]*10 != test.Delays[index] {
					t.Fatalf("frame %d delay: got %dms, want %dms", index, actual.Delay[index]*10, test.Delays[index])
				}

				// ffwebp emits full-canvas GIF frames; assert every composited pixel.
				assertPixels(t, actual.Image[index], expected)

				selections := []frameSelection{
					{flag: "--frame", value: strconv.Itoa(index)},
					{flag: "--time", value: strconv.Itoa(elapsed) + "ms"},
				}

				for _, selection := range selections {
					selected := filepath.Join(dir, "selected.png")

					run(t, icmd.Command(executable, "-s", "-i", input, "-o", selected, selection.flag, selection.value))
					assertPixels(t, readPNG(t, selected), expected)
				}

				elapsed += test.Delays[index]
			}
		})
	}
}

func TestCLI_CodecEncode(t *testing.T) {
	// One smoke test per encoder, independent of the number of input variants.
	for ext := range strings.FieldsSeq("avif bmp dds ff gif heic heif ico cur jpeg jxl pcx png apng pnm pbm pgm ppm pam qoi tga tif tiff webp xbm xpm") {
		t.Run(ext, func(t *testing.T) {
			dir := t.TempDir()
			mid := filepath.Join(dir, "encoded."+ext)
			back := filepath.Join(dir, "roundtrip.png")

			run(t, icmd.Command(executable, "-s", "-i", exampleJPEG, "-o", mid))
			run(t, icmd.Command(executable, "-s", "-i", mid, "-o", back))

			got := readPNG(t, back).Bounds()
			if got != image.Rect(0, 0, 120, 90) {
				t.Fatalf("bounds: got %v, want 120x90", got)
			}
		})
	}
}

func TestCLI_DDSTexturePreservation(t *testing.T) {
	for name := range strings.FieldsSeq("dds-cube-array.dds dds-volume.dds dds-typeless-hdr.dds") {
		t.Run(name, func(t *testing.T) {
			input := filepath.Join(fixturesDir, "inputs", name)
			output := filepath.Join(t.TempDir(), name)

			run(t, icmd.Command(executable, "-s", "-i", input, "-o", output, "--lossless"))

			expected, err := os.ReadFile(input)
			if err != nil {
				t.Fatal(err)
			}

			actual, err := os.ReadFile(output)
			if err != nil {
				t.Fatal(err)
			}

			if len(expected) < 148 || len(actual) != len(expected) {
				t.Fatalf("DDS size: got %d, want %d with a DX10 header", len(actual), len(expected))
			}

			if string(actual[:4]) != "DDS " || string(actual[84:88]) != "DX10" {
				t.Fatal("missing DDS/DX10 signature")
			}

			// Check dimensions and mip count independently of the DDS decoder.
			depth := max(1, binary.LittleEndian.Uint32(actual[24:28]))
			wantDepth := max(1, binary.LittleEndian.Uint32(expected[24:28]))

			if !bytes.Equal(actual[12:20], expected[12:20]) || depth != wantDepth || !bytes.Equal(actual[28:32], expected[28:32]) {
				t.Fatal("DDS dimensions or mip count changed")
			}

			// The DX10 extension carries format, dimension, cube/array and alpha metadata.
			if !bytes.Equal(actual[128:], expected[128:]) {
				t.Fatal("DDS metadata or native subresource payload changed")
			}
		})
	}
}

func TestCLI_DDSDropAlpha(t *testing.T) {
	cases := []ddsAlphaCase{
		{name: "straight", mode: "straight"},
		{name: "omitted"},
		{name: "auto", mode: "auto"},
		{name: "premultiplied", mode: "premultiplied", err: "premultiplied output requires an alpha channel"},
	}

	var expected []byte

	for _, test := range cases {
		t.Run(test.name, func(t *testing.T) {
			output := filepath.Join(t.TempDir(), "out.dds")
			arguments := []string{"-s", "-i", "fixtures/inputs/dds-premultiplied-srgb.dds", "-o", output, "--dds.format", "BC6H_UF16"}

			if test.mode != "" {
				arguments = append(arguments, "--dds.alpha", test.mode)
			}

			result := icmd.RunCmd(icmd.Command(executable, arguments...))

			if test.err != "" {
				result.Assert(t, icmd.Expected{ExitCode: 1, Err: test.err})

				_, err := os.Stat(output)
				if !os.IsNotExist(err) {
					t.Fatalf("rejected alpha mode published output: %v", err)
				}

				return
			}

			result.Assert(t, icmd.Success)

			actual, err := os.ReadFile(output)
			if err != nil {
				t.Fatal(err)
			}

			if len(actual) != 164 || string(actual[:4]) != "DDS " || string(actual[84:88]) != "DX10" || binary.LittleEndian.Uint32(actual[128:132]) != 95 {
				t.Fatal("expected one BC6H_UF16 block with a DX10 header")
			}

			if test.mode == "straight" {
				expected = actual
			} else if !bytes.Equal(actual, expected) {
				t.Fatal("alpha mode differs from explicit straight output")
			}
		})
	}
}

func TestCLI_DDSLosslessPrecision(t *testing.T) {
	t.Run("rgba8-to-rgba16-cube-array", func(t *testing.T) {
		input := "fixtures/inputs/dds-cube-array.dds"
		output := filepath.Join(t.TempDir(), "out.dds")

		run(t, icmd.Command(executable, "-s", "-i", input, "-o", output, "--lossless", "--dds.format", "R16G16B16A16_UNORM"))

		expected, err := os.ReadFile(input)
		if err != nil {
			t.Fatal(err)
		}

		actual, err := os.ReadFile(output)
		if err != nil {
			t.Fatal(err)
		}

		if len(expected) < 148 || len(actual) != 148+2*(len(expected)-148) {
			t.Fatalf("unexpected widened DDS size: input=%d, output=%d", len(expected), len(actual))
		}

		if string(actual[:4]) != "DDS " || string(actual[84:88]) != "DX10" || binary.LittleEndian.Uint32(actual[128:132]) != 11 {
			t.Fatal("expected RGBA16_UNORM with a DX10 header")
		}

		// Dimensions, depth, mips and both legacy/DX10 cube-array topology must survive.
		depth := max(1, binary.LittleEndian.Uint32(actual[24:28]))
		wantDepth := max(1, binary.LittleEndian.Uint32(expected[24:28]))

		if !bytes.Equal(actual[12:20], expected[12:20]) || depth != wantDepth || !bytes.Equal(actual[28:32], expected[28:32]) || !bytes.Equal(actual[108:116], expected[108:116]) || !bytes.Equal(actual[132:148], expected[132:148]) {
			t.Fatal("lossless conversion changed texture topology or alpha metadata")
		}

		for index, sample := range expected[148:] {
			actualSample := binary.LittleEndian.Uint16(actual[148+2*index:])
			want := uint16(sample) * 257

			if actualSample != want {
				t.Fatalf("sample %d: got %d, want %d", index, actualSample, want)
			}
		}
	})

	t.Run("rgba16-to-rgba8-rejected", func(t *testing.T) {
		output := filepath.Join(t.TempDir(), "out.dds")
		result := icmd.RunCmd(icmd.Command(executable, "-s", "-i", "fixtures/inputs/dds-rgba16.dds", "-o", output, "--lossless", "--dds.format", "R8G8B8A8_UNORM"))
		result.Assert(t, icmd.Expected{ExitCode: 1, Err: "--lossless prohibits lossy precision/range conversion"})

		_, err := os.Stat(output)
		if !os.IsNotExist(err) {
			t.Fatalf("rejected precision loss published output: %v", err)
		}
	})
}

